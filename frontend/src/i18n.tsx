const dictionaries = {
  'zh-CN': zh,
  'en-US': en,
} as const

function resolveValue(tree: TranslationTree, key: string): TranslationValue | undefined {
  return key.split('.').reduce<TranslationValue | TranslationTree | undefined>((current, part) => {
    if (!current || typeof current === 'string' || Array.isArray(current)) return undefined
    return (current as TranslationTree)[part]
  }, tree) as TranslationValue | undefined
}

export function translate(language: LanguageMode, key: string): TranslationValue {
  return resolveValue(dictionaries[language], key) ?? resolveValue(zh, key) ?? key
}

function interpolate(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`))
}

export function useI18n() {
  const language = useAppStore((state) => state.languageMode)
  return useMemo(() => ({
    language,
    isEnglish: language === 'en-US',
    t: (key: string) => translate(language, key),
    text: (key: string) => String(translate(language, key)),
    format: (key: string, params: Record<string, string | number>) => interpolate(String(translate(language, key)), params),
    list: (key: string) => {
      const value = translate(language, key)
      return Array.isArray(value) ? [...value] : []
    },
  }), [language])
}

export function LocalizedText({ children, className, as = 'span', variant = 'fade' }: LocalizedTextProps) {
  const language = useAppStore((state) => state.languageMode)
  const MotionTag = as === 'div' ? motion.div : as === 'p' ? motion.p : motion.span
  const isRoll = variant === 'roll'
  const motionProps = isRoll
    ? {
        initial: { opacity: 0, y: language === 'en-US' ? 10 : -10 },
        animate: { opacity: 1, y: 0 },
        exit: { opacity: 0, y: language === 'en-US' ? -10 : 10 },
        transition: { duration: 0.36, ease: [0.22, 1, 0.36, 1] as const },
      }
    : {
        initial: { opacity: 0, y: 2 },
        animate: { opacity: 1, y: 0 },
        exit: { opacity: 0, y: -2 },
        transition: { duration: 0.16, ease: 'easeOut' as const },
      }

  if (isRoll) {
    const WrapperTag = as === 'div' ? 'div' : as === 'p' ? 'p' : 'span'
    const splitText = typeof children === 'string' || typeof children === 'number' ? String(children) : ''
    if (!splitText) {
      return (
        <WrapperTag className={`localized-roll-clip${className ? ` ${className}` : ''}`}>
          {children}
        </WrapperTag>
      )
    }
    return (
      <WrapperTag className={`localized-roll-clip${className ? ` ${className}` : ''}`}>
        <AnimatePresence mode="wait" initial={false}>
          <MotionTag
            key={language}
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0, y: language === 'en-US' ? -5 : 5 }}
            transition={{ duration: 0.16, ease: 'easeOut' }}
            className="localized-roll-text"
          >
            <SplitText
              text={splitText}
              tag="span"
              splitType="chars"
              delay={18}
              duration={0.46}
              from={{ opacity: 0, y: 14 }}
              to={{ opacity: 1, y: 0 }}
              textAlign="left"
            />
          </MotionTag>
        </AnimatePresence>
      </WrapperTag>
    )
  }

  return (
    <AnimatePresence mode="wait" initial={false}>
      <MotionTag
        key={language}
        {...motionProps}
        className={className}
      >
        {children}
      </MotionTag>
    </AnimatePresence>
  )
}

const DEFAULT_ROLE_NAME_KEYS: Record<string, string> = {
  director: 'debate.directorRole',
  analyst: 'debate.analystRole',
  critic: 'debate.criticRole',
  researcher: 'debate.researcherRole',
  investor: 'debate.investorRole',
}

const DEFAULT_ROLE_NAME_ZH: Record<string, string> = {
  director: '导演',
  analyst: '产品经理',
  critic: '杠精',
  researcher: '调研员',
  investor: '投资人',
}

export function localizeRoleName(role: string, storedName: string | undefined, language: LanguageMode): string {
  const key = DEFAULT_ROLE_NAME_KEYS[role]
  if (!key) return storedName || role
  const defaultZh = DEFAULT_ROLE_NAME_ZH[role]
  if (!storedName || storedName === defaultZh || storedName === translate('en-US', key)) {
    return String(translate(language, key))
  }
  return storedName
}
